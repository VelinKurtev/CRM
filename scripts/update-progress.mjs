#!/usr/bin/env node
// Writes a progress summary (bars + per-phase table) into CRM-User-Stories.md from its checkboxes.
//
//   node scripts/update-progress.mjs           update the file
//   node scripts/update-progress.mjs --check   exit 1 if the summary is out of date (for CI)
//
// Only story lines ("- [x] **US-012 – …") are counted, not their indented sub-items. The summary
// lives between the two marker comments below; if they are missing it is inserted above the first "---".

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const FILE = fileURLToPath(new URL('../CRM-User-Stories.md', import.meta.url))
const START = '<!-- progress:start (generated by scripts/update-progress.mjs, do not edit by hand) -->'
const END = '<!-- progress:end -->'

const bar = (done, total, width) => {
  const filled = total === 0 ? 0 : Math.round((done / total) * width)
  return '🟩'.repeat(filled) + '⬜'.repeat(width - filled)
}
const percent = (done, total) => (total === 0 ? 0 : Math.round((done / total) * 100))

/** Count stories per `## Phase …` heading. */
export function countStories(markdown) {
  const phases = []
  for (const line of markdown.split('\n')) {
    const heading = line.match(/^## (.+)$/)
    if (heading) phases.push({ name: heading[1].trim(), done: 0, total: 0 })
    const story = line.match(/^- \[( |x|X)\] \*\*US-\d+/)
    if (story && phases.length > 0) {
      phases.at(-1).total++
      if (story[1] !== ' ') phases.at(-1).done++
    }
  }
  return phases.filter((p) => p.total > 0)
}

export function renderSummary(phases) {
  const done = phases.reduce((n, p) => n + p.done, 0)
  const total = phases.reduce((n, p) => n + p.total, 0)
  const rows = phases.map(
    (p) =>
      `| ${p.name} | ${bar(p.done, p.total, 10)} ${String(percent(p.done, p.total)).padStart(3)}% | ${p.done} / ${p.total} |`,
  )
  return [
    START,
    `**Overall progress: ${done} of ${total} stories (${percent(done, total)}%)**`,
    '',
    `${bar(done, total, 20)} ${percent(done, total)}%`,
    '',
    '| Phase | Progress | Done |',
    '| --- | --- | --- |',
    ...rows,
    END,
  ].join('\n')
}

export function withSummary(markdown) {
  const summary = renderSummary(countStories(markdown))
  const block = new RegExp(`${START.replace(/[()/]/g, '\\$&')}[\\s\\S]*?${END}`)
  if (block.test(markdown)) return markdown.replace(block, () => summary)
  const firstRule = markdown.indexOf('\n---\n')
  if (firstRule === -1) return `${markdown.trimEnd()}\n\n${summary}\n`
  return `${markdown.slice(0, firstRule).trimEnd()}\n\n${summary}\n${markdown.slice(firstRule)}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const current = readFileSync(FILE, 'utf8')
  const updated = withSummary(current)
  if (process.argv.includes('--check')) {
    if (updated !== current) {
      console.error('CRM-User-Stories.md progress is out of date. Run: node scripts/update-progress.mjs')
      process.exit(1)
    }
    console.log('Progress summary is up to date.')
  } else if (updated === current) {
    console.log('Progress summary already up to date.')
  } else {
    writeFileSync(FILE, updated)
    console.log('Updated progress summary in CRM-User-Stories.md')
  }
}
